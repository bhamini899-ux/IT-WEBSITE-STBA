// Helper to compute faculty average attendance rate
export function getAverageFacultyAttendance(facultyList: Teacher[] = INITIAL_TEACHERS): number {
  if (!facultyList || facultyList.length === 0) return 97.1;
  const total = facultyList.reduce((acc, t) => acc + (t.attendanceRate || 95), 0);
  return Number((total / facultyList.length).toFixed(1));
}

